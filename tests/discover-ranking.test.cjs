const assert=require("node:assert/strict");
const {profile,rank,sort}=require("../assets/discover-ranking.js");
const days=["monday","tuesday","wednesday","thursday","friday","saturday","sunday"];
const complete={id:"a",name:"Complete",category:"Café",logo_path:"logo",cover_path:"cover",location:"Angeles City",latitude:15.1,longitude:120.5,description:"Cafe",phone:"123",weekly_hours:Object.fromEntries(days.map(d=>[d,{open:"08:00",close:"18:00"}]))};
const media={gallery_count:1,menu_count:1};
assert.equal(profile(complete,media).score,100);
assert.equal(profile({id:"b",name:"Empty"}).score,0);
assert.equal(profile({...complete,logo_path:" "},media).score,80);
assert.equal(profile({...complete,weekly_hours:{monday:{open:"08:00",close:"18:00"}}},media).score,85);
assert.equal(profile({...complete,weekly_hours:Object.fromEntries(days.map(d=>[d,{closed:true}]))},media).score,100);
assert.equal(profile({...complete,latitude:100},media).score,85);
assert.equal(profile({...complete,mobile_service:true,location:"",latitude:null,longitude:null,service_area:"Pampanga"},{gallery_count:1}).score,100);
assert.ok(rank(complete,{...media,review_count:100,average_rating:4.8}).rating>rank(complete,{...media,review_count:1,average_rating:5}).rating);
assert.equal(rank(complete,{...media,review_count:0}).rating,3.5);
assert.equal(rank(complete,{...media,follower_count:100}).score,rank(complete,{...media,follower_count:10000}).score);
assert.equal(sort([{id:"b",name:"Empty"},complete],b=>b.id==="a"?media:{follower_count:10000,review_count:100,average_rating:5})[0].id,"a");
assert.equal(sort([{...complete,id:"b"},{...complete,id:"a"}],()=>media)[0].id,"a");
assert.equal(rank({...complete,logo_path:null,cover_path:null},media).tier,1);
assert.equal(rank({id:"empty"},{}).tier,0);
console.log("14 Discover ranking assertions passed");
